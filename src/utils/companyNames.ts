/**
 * Returns the full official corporate name for a given B3 stock.
 * Eliminates duplicate ticker display by resolving true corporate name.
 */
export function getCompanyFullName(ticker: string, existingName?: string | null): string {
  const cleanTicker = (ticker || '').toUpperCase().trim();
  const root = cleanTicker.replace(/[0-9]+$/, '');

  // If a valid custom name is supplied that is NOT simply the ticker repeated
  if (
    existingName &&
    existingName.trim().length > 0 &&
    existingName.trim().toUpperCase() !== cleanTicker &&
    existingName.trim().toUpperCase() !== root
  ) {
    return existingName.trim();
  }

  // 1. Direct match by full ticker (e.g. PETR4)
  if (B3_COMPANIES_DICTIONARY[cleanTicker]) {
    return B3_COMPANIES_DICTIONARY[cleanTicker];
  }

  // 2. Match by root (e.g. PETR -> Petróleo Brasileiro S.A. - Petrobras)
  if (B3_ROOT_COMPANIES[root]) {
    return B3_ROOT_COMPANIES[root];
  }

  // 3. If ticker has a recognizable suffix like 3, 4, 11
  return existingName && existingName.trim().length > 0
    ? existingName.trim()
    : cleanTicker;
}
